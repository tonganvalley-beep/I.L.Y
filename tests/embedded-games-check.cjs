// Run against npm start with NODE_PATH pointing to the installed Playwright package.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const base=process.env.ILY_TEST_URL||'http://127.0.0.1:8097';
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:800}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    page.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url())});
    const scene=async id=>{
      await page.goto(`${base}/game/index.html?entry=chapters&player=scene-preview&scene=${id}`);
      await page.waitForFunction(()=>window.ILY?.mountPhoto&&document.querySelector('#stage').children.length>0);
    };
    fs.mkdirSync('outputs/integration',{recursive:true});
    await scene('ch1_battle');
    const xp=page.frameLocator('.photo-embed iframe');
    await xp.locator('.icon').filter({hasText:'games'}).dblclick();
    await xp.locator('.icon.small').filter({hasText:'红心弹幕'}).dblclick();
    const heart=xp.frameLocator('.game-frame');
    await heart.getByRole('button',{name:'开始关卡',exact:true}).click();
    assert.ok(await heart.locator('canvas').isVisible());
    await page.screenshot({path:'outputs/integration/computer-heart.png'});
    await page.locator('#menu-toggle').click();
    await heart.locator('canvas').evaluate(()=>{});
    await page.waitForFunction(()=>document.querySelector('.photo-embed iframe').contentWindow.document.querySelector('.game-frame').contentWindow.ILY_HOST_PAUSED===true);
    await page.locator('#menu-close').click();
    await page.waitForFunction(()=>document.querySelector('.photo-embed iframe').contentWindow.document.querySelector('.game-frame').contentWindow.ILY_HOST_PAUSED===false);
    await xp.locator('.game-win .win-close').click();
    await xp.locator('.icon.small').filter({hasText:'三维弹球'}).dblclick();
    await xp.frameLocator('.game-frame').locator('canvas').waitFor();
    await page.screenshot({path:'outputs/integration/computer-pinball.png'});
    await page.getByRole('button',{name:'离开电脑 · 继续剧情'}).click();
    await page.waitForFunction(()=>!document.querySelector('.photo-embed'));
    await page.waitForFunction(()=>document.querySelector('#stage').textContent.includes('七点半'));

    await scene('ch2_photo');
    const photo=page.frameLocator('.photo-embed iframe');
    await photo.getByRole('button',{name:'开始跟拍'}).click();
    const frame=page.frames().find(f=>f.url().includes('photo-rhythm/index.html'));
    await frame.waitForFunction(()=>!document.querySelector('#bgm').paused);
    await frame.evaluate(()=>{document.querySelector('#bgm').currentTime=5});
    await photo.locator('.note').first().waitFor();
    await page.screenshot({path:'outputs/integration/photo-playing.png'});
    await page.getByRole('button',{name:'暂停',exact:true}).click();
    await photo.locator('#pause:not(.hidden)').waitFor();
    assert.equal(await frame.evaluate(()=>document.querySelector('#bgm').paused),true);
    await photo.getByRole('button',{name:'继续拍摄',exact:true}).click();
    await frame.waitForFunction(()=>!document.querySelector('#bgm').paused);
    // Drive the media end event without waiting through the 222-second track.
    await frame.evaluate(()=>document.querySelector('#bgm').dispatchEvent(new Event('ended')));
    await photo.locator('#result:not(.hidden)').waitFor({timeout:10000});
    await page.screenshot({path:'outputs/integration/photo-result.png'});
    await page.locator('#menu-toggle').click();
    await page.locator('#quick-save').click();
    const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('ily-save-v2:scene-preview:quick-1')));
    assert.equal(saved.state.node,'ch2_photo');
    assert.equal(saved.state.flags.PHOTO_COMPLETED,true);
    assert.ok(Number.isFinite(saved.state.flags.PHOTO_RESULT.score));
    await page.locator('#menu-close').click();
    await photo.getByRole('button',{name:'再拍一卷'}).click();
    await frame.waitForFunction(()=>!document.querySelector('#bgm').paused&&document.querySelector('#bgm').currentTime<2);
    await page.getByRole('button',{name:'收起相机 · 继续散步'}).click();
    await page.waitForFunction(()=>!document.querySelector('.photo-embed'));
    await page.waitForFunction(()=>document.querySelector('#stage').textContent.includes('这样啊'));
    await page.locator('#rollback').click();
    await photo.locator('#intro:not(.hidden)').waitFor();
    await page.goto(`${base}/game/index.html?entry=chapters&player=scene-preview&slot=quick-1`);
    await photo.locator('#start').click();
    const restored=page.frames().find(f=>f.url().includes('photo-rhythm/index.html'));
    await restored.waitForFunction(()=>!document.querySelector('#bgm').paused);
    await restored.evaluate(()=>document.querySelector('#bgm').dispatchEvent(new Event('ended')));
    await photo.locator('#continue').click();
    await page.waitForFunction(()=>!document.querySelector('.photo-embed'));

    await scene('ch1_g1');
    await page.locator('.rpg-canvas').waitFor();
    await page.screenshot({path:'outputs/integration/rpg-markers.png'});
    await page.evaluate(()=>ILY.openMemories());
    await page.locator('.mem-dialog[open]').waitFor();
    await page.screenshot({path:'outputs/integration/memories.png'});
    await page.locator('.mem-dialog .mem-head button').click();
    assert.equal(await page.locator('.mem-dialog').isVisible(),false);
    await scene('ch2_g2');
    await page.locator('.rpg-menu-toggle').click();
    await page.getByRole('button',{name:'自动完成当前探索'}).click();
    await photo.locator('#intro:not(.hidden)').waitFor();
    await page.setViewportSize({width:800,height:600});
    await scene('ch2_photo');
    await photo.getByRole('button',{name:'开始跟拍'}).waitFor();
    await page.screenshot({path:'outputs/integration/photo-small.png'});
    await page.setViewportSize({width:1280,height:800});
    await scene('fin_s03');
    const boss=page.frameLocator('.boss-frame');
    await boss.locator('#start:not([disabled])').waitFor({timeout:60000});
    const bossFrame=page.frames().find(f=>f.url().includes('minigames/boss/final-release/index.html'));
    assert.ok(bossFrame);
    await bossFrame.evaluate(()=>document.fonts.ready);
    await boss.locator('#start').click();
    await boss.locator('body[data-state=playing]').waitFor({timeout:15000});
    await page.screenshot({path:'outputs/integration/boss-final-release.png'});
    await boss.locator('.toolbar [data-story-skip]').click();
    await page.waitForFunction(()=>!document.querySelector('.boss-frame'));
    await page.evaluate(()=>{
      localStorage.setItem('mygame-token','scene-preview');
      const key='ily-save-v2:scene-preview:quick-1',save=JSON.parse(localStorage.getItem(key));
      save.state.flags.memories.story.push('s01_intro');
      localStorage.setItem(key,JSON.stringify(save));
    });
    await page.goto(`${base}/sign&log/game.html`);
    await page.waitForFunction(()=>typeof window.openMemoriesMain==='function');
    await page.evaluate(()=>openMemoriesMain());
    await page.locator('#memoriesDialog [data-tab=story]').click();
    const published=await page.evaluate(()=>ILY_SCRIPT_EDITS.s01_intro.text);
    assert.ok((await page.locator('#memoriesDialog').textContent()).includes(published));
    await page.locator('#memoriesDialog [data-tab=gallery]').click();
    assert.deepEqual(errors,[]);
    console.log('XP games, rhythm start/pause/replay/return, final Boss, RPG markers and memories passed.');
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});

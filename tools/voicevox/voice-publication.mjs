import { createHash } from 'node:crypto';
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { isValidWav } from './batch-queue.mjs';

const hash = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
const stableFilename = lineId => `${createHash('sha256').update(lineId).digest('hex').slice(0, 20)}.wav`;
const manifestPrefix = '// Generated by the VOICEVOX editor. Consumed by the game VoicePlayer; publish only reviewed, current audio.\nwindow.ILY_VOICE_MANIFEST = ';

async function readManifest(file) {
  try {
    const script = await readFile(file, 'utf8');
    if (!script.startsWith(manifestPrefix) || !script.endsWith(';\n')) return null;
    const manifest = JSON.parse(script.slice(manifestPrefix.length, -2));
    return manifest?.schemaVersion === 1 && manifest.entries && typeof manifest.entries === 'object' ? manifest : null;
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

async function atomicWrite(file, content) {
  await mkdir(dirname(file), { recursive: true });
  const temp = `${file}.${process.pid}.tmp`;
  await writeFile(temp, content, 'utf8');
  await rename(temp, file);
}

export async function publishVoiceManifest({ project, source, queue, outputDir, manifestFile, lineIds, recoverOnly = false }) {
  if (!project?.projectRevision) throw Object.assign(new Error('请先保存配音工程'), { code: 'PROJECT_NOT_SAVED' });
  const requested = new Set(lineIds || []);
  if (!requested.size && !recoverOnly) throw Object.assign(new Error('没有选择要发布的台词'), { code: 'EMPTY_PUBLISH' });
  const sources = new Map(source.lines.map(line => [line.lineId, line]));
  const projects = new Map((project.lines || []).map(line => [line.lineId, line]));
  const tasks = queue.state.tasks;
  const matchingTask = line => [...tasks].reverse().find(value => value.lineId === line.lineId && value.status === 'completed' &&
    value.speechText === line.speechText?.trim() && value.styleId === Number(line.styleId) && value.queryHash === hash(line.audioQuery));
  const entries = {};
  const assets = [];
  for (const lineId of requested) {
    const line = projects.get(lineId), current = sources.get(lineId);
    if (!line || !current || line.sourceFingerprint !== current.sourceFingerprint) throw Object.assign(new Error(`台词 ${lineId} 已删除或源文已变化，请先同步并保存`), { code: 'SOURCE_STALE' });
    if (!line.voiceEnabled) throw Object.assign(new Error(`台词 ${lineId} 未勾选“纳入配音”`), { code: 'VOICE_EXCLUDED' });
    if (line.translationStatus !== 'proofread' || !line.speechText?.trim()) throw Object.assign(new Error(`台词 ${lineId} 的日语尚未校对，请校对并保存后再发布`), { code: 'TRANSLATION_NOT_READY' });
    if (line.renderStale || !line.audioQuery) throw Object.assign(new Error(`台词 ${lineId} 的音频已过期`), { code: 'AUDIO_STALE' });
    const task = matchingTask(line);
    if (!task) throw Object.assign(new Error(`台词 ${lineId} 没有与当前文本及调音一致的完成音频`), { code: 'AUDIO_NOT_READY' });
    const audio = await readFile(join(queue.renderDir, task.outputFile));
    if (!isValidWav(audio)) throw Object.assign(new Error(`台词 ${lineId} 的 WAV 无效`), { code: 'INVALID_WAV' });
    const file = stableFilename(lineId);
    assets.push({ file, audio });
    entries[lineId] = {
      file: `assets/audio/voices/published/${file}`,
      sourceFingerprint: current.sourceFingerprint,
      renderHash: task.cacheKey,
      styleId: task.styleId,
      speaker: current.speaker,
      kind: current.kind,
      engine: task.engineIdentity || null
    };
  }
  await mkdir(outputDir, { recursive: true });
  const previous = await readManifest(manifestFile);
  for (const [lineId, entry] of Object.entries(previous?.entries || {})) {
    if (requested.has(lineId)) continue;
    const current = sources.get(lineId);
    const file = stableFilename(lineId);
    if (!current || entry.sourceFingerprint !== current.sourceFingerprint || entry.file !== `assets/audio/voices/published/${file}`) continue;
    try {
      if (isValidWav(await readFile(join(outputDir, file)))) entries[lineId] = entry;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
  }
  // A later partial publish may have overwritten an older manifest. Stable-name files only
  // exist after publication, so recover those snapshots by matching their exact queue render.
  for (const [lineId, line] of projects) {
    if (requested.has(lineId) || entries[lineId]) continue;
    const current = sources.get(lineId);
    if (!current || line.sourceFingerprint !== current.sourceFingerprint) continue;
    const file = stableFilename(lineId);
    let published;
    try { published = await readFile(join(outputDir, file)); }
    catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    if (!isValidWav(published)) continue;
    const candidates = tasks.filter(task => task.lineId === lineId && task.status === 'completed').reverse();
    let task = null;
    for (const candidate of candidates) {
      try {
        const rendered = await readFile(join(queue.renderDir, candidate.outputFile));
        if (published.equals(rendered)) { task = candidate; break; }
      } catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
    if (!task) continue;
    entries[lineId] = {
      file: `assets/audio/voices/published/${file}`,
      sourceFingerprint: current.sourceFingerprint,
      renderHash: task.cacheKey,
      styleId: task.styleId,
      speaker: current.speaker,
      kind: current.kind,
      engine: task.engineIdentity || null
    };
  }
  for (const { file, audio } of assets) {
    const target = join(outputDir, file);
    const temp = `${target}.${process.pid}.tmp`;
    await writeFile(temp, audio);
    await rename(temp, target);
  }
  const manifest = { schemaVersion: 1, sourceRevision: source.sourceRevision, projectRevision: project.projectRevision, generatedAt: new Date().toISOString(), entries };
  const script = `${manifestPrefix}${JSON.stringify(manifest, null, 2)};\n`;
  await atomicWrite(manifestFile, script);
  return { count: assets.length, totalCount: Object.keys(entries).length, manifest, manifestFile };
}

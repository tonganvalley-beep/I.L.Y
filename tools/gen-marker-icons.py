def hex_rgb(value):
    value = value.lstrip('#')
    return tuple(int(value[i:i + 2], 16) for i in (0, 2, 4))


def write_png(path, rows, size):
    raw = b''.join(b'\x00' + bytes(row) for row in rows)

    def chunk(kind, data):
        payload = kind + data
        return struct.pack('>I', len(data)) + payload + struct.pack('>I', zlib.crc32(payload) & 0xffffffff)

    header = b'\x89PNG\r\n\x1a\n'
    ihdr = struct.pack('>IIBBBBB', size, size, 8, 6, 0, 0, 0)
    png = header + chunk(b'IHDR', ihdr) + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')
    with open(path, 'wb') as fh:
        fh.write(png)


def render(icon_name, color):
    grid = ICONS[icon_name]
    r, g, b = hex_rgb(color)
    size = GRID * SCALE
    rows = []
    for y in range(size):
        row = []
        for x in range(size):
            on = grid[y // SCALE][x // SCALE] == '#'
            row += [r, g, b, 255] if on else [0, 0, 0, 0]
        rows.append(row)
    return rows, size


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for kind, icon in KIND_ICON.items():
        rows, size = render(icon, COLORS[kind])
        path = os.path.join(OUT_DIR, 'marker-%s.png' % kind)
        write_png(path, rows, size)
        print('wrote', os.path.relpath(path, ROOT), size)
    print('done ->', OUT_DIR)


if __name__ == '__main__':
    main()

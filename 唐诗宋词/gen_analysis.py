def extract_poems(html):
    out = []
    for m in re.finditer(r'<div class="poem">.*?</div>', html, flags=re.S):
        block = m.group(0)
        tm = re.search(r'<h2 id="poem\d">(.*?)</h2>', block)
        title = tm.group(1) if tm else '?'
        cipai = None
        am = re.search(r'<p class="author-line">(.*?)</p>', block, flags=re.S)
        if am:
            cm = re.search(r'<span class="cipai">(.*?)</span>', am.group(1))
            if cm: cipai = cm.group(1)
        cb = re.sub(r'<p class="author-line">.*?</p>', '', block, flags=re.S)
        cb = re.sub(r'<div class="shangxi">.*?</div>', '', cb, flags=re.S)
        lines = re.findall(r'<p>(.*?)</p>', cb, flags=re.S)
        lines = [re.sub(r'<.*?>', '', l).strip() for l in lines]
        lines = [l for l in lines if l]
        out.append({'title': title, 'cipai': cipai, 'lines': lines})
    return out


def modify_main(poet, html):
    folder = poet['folder']
    # 1) 移除赏析块
    html = re.sub(r'\s*<div class="shangxi">.*?</div>', '', html, flags=re.S)
    # 2) 本篇目录 #poemN -> 赏析页
    for i, p in enumerate(poet['poems'], start=1):
        html = html.replace(f'<a href="#poem{i}">', f'<a href="{folder}/{p["file"]}.htm">')
    # 3) 整个 .poem 卡片包成可点击链接
    def wrap(m):
        block = m.group(0)
        im = re.search(r'id="(poem\d)"', block)
        if not im:
            return block
        idx = int(im.group(1)[4:]) - 1
        file = poet['poems'][idx]['file']
        return f'<a href="{folder}/{file}.htm" class="poem-link">{block}<p class="poem-hint">点击查看赏析 ›</p></a>'
    html = re.sub(r'<div class="poem">.*?</div>', wrap, html, flags=re.S)
    return html

def main():
    created = []
    modified = []
    for poet in POETS:
        basedir = os.path.join(ROOT, poet['dir'])
        main_path = os.path.join(basedir, poet['main'])
        folder_path = os.path.join(basedir, poet['folder'])
        os.makedirs(folder_path, exist_ok=True)

        html = open(main_path, 'r', encoding='utf-8').read()
        exts = extract_poems(html)
        assert len(exts) == len(poet['poems']), f"{poet['main']} 抽取到 {len(exts)} 首，期望 {len(poet['poems'])} 首"

        for idx in range(len(poet['poems'])):
            page = analysis_page(poet, idx, exts[idx])
            out = os.path.join(folder_path, poet['poems'][idx]['file'] + '.htm')
            open(out, 'w', encoding='utf-8', newline='').write(page)
            created.append(os.path.relpath(out, ROOT))

        new_html = modify_main(poet, html)
        open(main_path, 'w', encoding='utf-8', newline='').write(new_html)
        modified.append(poet['main'])

    print("已生成赏析页：")
    for c in created:
        print("  ", c)
    print("已改写主页：", ", ".join(modified))

if __name__ == '__main__':
    main()
